#!/usr/bin/env Rscript

# =============================================================================
# TVP-GVAR INTEREST-RATE CHANNEL DIAGNOSTIC (NO MCMC)
#
# Purpose
# -------
# Test whether the positive medium-horizon equity response to a +GPR shock is
# supported by the endogenous decline in policy/short rates.
#
# This script uses the already-estimated dominant-unit [GPR,VIX] posterior.
# It DOES NOT re-estimate the model.
#
# Scenarios
# ---------
# FULL
#   Original saved model.
#
# RATE_CF1_zero_current_foreign_rate_to_equity
#   Set Lambda0(foreign_r)=0 only in each country equity equation.
#
# RATE_CF2_zero_current_and_lag1_foreign_rate_to_equity
#   Set Lambda0/Lambda1(foreign_r)=0 only in each country equity equation.
#   This measures the direct weakly-exogenous foreign-rate loading into equity.
#
# RATE_CF3_freeze_all_country_rate_path
#   Strong path intervention. For the GPR IRF, every country r response is fixed
#   to exactly zero at every horizon. The country rate equations are replaced by
#   the constraints r_i(h)=0, while all non-rate equations remain active.
#   This removes BOTH domestic and international propagation generated by the
#   endogenous rate response. It is the main test of the hypothesis:
#       GPR -> rates fall -> equities are supported / recover.
#
# Interpretation of RATE_CF3
# --------------------------
# monetary_support = FULL equity response - rate-frozen equity response
#   > 0 : endogenous rate response raises/supports equity relative to no-rate move
#   < 0 : endogenous rate response depresses equity relative to no-rate move
#
# Important caveat
# ----------------
# RATE_CF3 is a post-estimation path intervention / mechanism diagnostic, not a
# newly estimated structural monetary-policy model and not a causal policy rule.
# =============================================================================

