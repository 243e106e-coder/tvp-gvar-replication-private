# -----------------------------------------------------------------------------
# Main loop
# -----------------------------------------------------------------------------
cat("\n============================================================\n")
cat(" TVP-GVAR INTEREST-RATE CHANNEL DIAGNOSTIC — NO MCMC\n")
cat(" Posterior: ", posterior_file, "\n", sep="")
cat(" IRF:       ", irf_file, "\n", sep="")
cat(" Dates:     ", paste(selected_dates, collapse=", "), "\n", sep="")
cat(" Horizon:   0-", horizon, "\n", sep="")
cat(" Focus h:   ", paste(focus_h, collapse=", "), "\n", sep="")
cat(" Shock:     +", shock_pct, "% GL_gpr\n", sep="")
cat("============================================================\n\n")

for (d_i in seq_along(selected_dates)) {
  ddate <- selected_dates[[d_i]]
  tt <- match(ddate, irf_dates)
  draws <- which(stable_mask[tt,])
  if (!length(draws)) {
    warning("No original stable draws at ", ddate, "; skipping.")
    next
  }
  if (max_draws_per_date > 0L && length(draws) > max_draws_per_date) draws <- draws[seq_len(max_draws_per_date)]
  used_draw[d_i,draws] <- TRUE
  cat("Date ", ddate, ": using ", length(draws), "/", sum(stable_mask[tt,]), " original stable draws\n", sep="")

  for (jj in seq_along(draws)) {
    draw <- draws[[jj]]
    base_state <- build_state(tt, draw, "FULL")
    base_path <- make_structural_irf(base_state, horizon, shock_pct)

    saved <- IRF_post[tt, , seq_len(horizon+1L), draw, drop=FALSE]
    saved <- matrix(saved, nrow=length(var_names), ncol=horizon+1L, dimnames=list(var_names,as.character(0:horizon)))
    err <- max(abs(base_path-saved), na.rm=TRUE)
    max_baseline_reproduction_error <- max(max_baseline_reproduction_error, err)
    if (!is.finite(err) || err > 1e-7) {
      stop("Baseline reconstruction mismatch at ", ddate, ", draw ", draw, ". max abs error = ", signif(err,8))
    }

    paths <- list(FULL=base_path)
    rhos <- list(FULL=base_state$rho)
    oks <- list(FULL=TRUE)

    # Coefficient switch-offs.
    for (scenario in c("RATE_CF1_zero_current_foreign_rate_to_equity", "RATE_CF2_zero_current_and_lag1_foreign_rate_to_equity")) {
      ans <- tryCatch({
        st <- build_state(tt, draw, scenario)
        pa <- make_structural_irf(st, horizon, shock_pct)
        list(ok=TRUE, path=pa, rho=st$rho)
      }, error=function(e) {
        warning("Counterfactual failed: date=", ddate, ", draw=", draw, ", scenario=", scenario, " | ", conditionMessage(e))
        list(ok=FALSE, path=NULL, rho=NA_real_)
      })
      if (ans$ok) paths[[scenario]] <- ans$path
      rhos[[scenario]] <- ans$rho
      oks[[scenario]] <- ans$ok
    }

    # Strong path intervention.
    scenario <- "RATE_CF3_freeze_all_country_rate_path"
    ans <- tryCatch({
      z <- make_rate_frozen_irf(base_state, horizon, shock_pct)
      list(ok=TRUE, path=z$path, rho=z$rho)
    }, error=function(e) {
      warning("Rate-path intervention failed: date=", ddate, ", draw=", draw, " | ", conditionMessage(e))
      list(ok=FALSE, path=NULL, rho=NA_real_)
    })
    if (ans$ok) paths[[scenario]] <- ans$path
    rhos[[scenario]] <- ans$rho
    oks[[scenario]] <- ans$ok

    # Diagnostics per scenario.
    for (scenario in scenarios) {
      s_i <- match(scenario, scenarios)
      solve_ok[d_i,s_i,draw] <- isTRUE(oks[[scenario]])
      rho_arr[d_i,s_i,draw] <- rhos[[scenario]]
    }

    # Baseline rate response: rates are level variables, so DO NOT cumulate.
    for (c_i in seq_along(country_units)) {
      vv <- paste0(country_units[[c_i]], "_r")
      v_i <- match(vv, var_names)
      z <- as.numeric(base_path[v_i,])
      for (h_i in seq_along(focus_h)) {
        h <- focus_h[[h_i]]
        rate_direct[d_i,c_i,h_i,draw] <- z[h+1L]
      }
    }

    # Equity direct and cumulative responses.
    for (scenario in scenarios) {
      if (is.null(paths[[scenario]])) next
      s_i <- match(scenario, scenarios)
      path <- paths[[scenario]]
      for (c_i in seq_along(country_units)) {
        vv <- paste0(country_units[[c_i]], "_deq")
        v_i <- match(vv, var_names)
        z <- as.numeric(path[v_i,])
        cz <- cumsum(z)
        for (h_i in seq_along(focus_h)) {
          h <- focus_h[[h_i]]
          eq_direct[d_i,s_i,c_i,h_i,draw] <- z[h+1L]
          eq_cumulative[d_i,s_i,c_i,h_i,draw] <- cz[h+1L]
        }
      }
    }

    if (jj %% 25L == 0L || jj == length(draws)) {
      cat("  ", ddate, ": draw ", jj, "/", length(draws), " complete\n", sep="")
    }
  }
}

