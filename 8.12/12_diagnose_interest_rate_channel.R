split_alpha <- function(A) {
  if (length(dim(A)) != 3L) stop("Single-draw ALPHA must be [time, coefficient, equation].")
  tags <- dimnames(A)[[2]]
  eq <- dimnames(A)[[3]]
  if (is.null(tags) || is.null(eq)) stop("ALPHA lacks coefficient/equation dimnames.")

  block <- function(tag, optional = FALSE) {
    ii <- which(tags == tag)
    if (!length(ii)) {
      if (!optional) stop("Missing coefficient block: ", tag)
      return(array(0, dim = c(dim(A)[1], 0L, dim(A)[3])))
    }
    A[, ii, , drop = FALSE]
  }

  lag_tags <- grep("^Ylag[0-9]+$", unique(tags), value = TRUE)
  if (!length(lag_tags)) stop("No domestic lag blocks in ALPHA.")
  lag_nums <- sort(unique(as.integer(sub("^Ylag", "", lag_tags))))
  if (anyNA(lag_nums) || !identical(lag_nums, seq_len(max(lag_nums)))) {
    stop("Domestic lag labels are not contiguous.")
  }
  p <- max(lag_nums)

  list(
    Lambda0 = block("Wex", optional = TRUE),
    Lambda = lapply(seq_len(p), function(j) block(paste0("Wexlag", j), optional = TRUE)),
    Theta = lapply(seq_len(p), function(j) block(paste0("Ylag", j))),
    p = p,
    eq = eq
  )
}

slice_coef <- function(arr, tt, nrow_out) {
  if (dim(arr)[2] == 0L) return(matrix(0, nrow = nrow_out, ncol = 0L))
  z <- arr[tt, , , drop = FALSE]
  z <- matrix(z, nrow = dim(arr)[2], ncol = nrow_out)
  t(z)
}

get_W <- function(i, cc) {
  if (!is.null(names(globalG)) && cc %in% names(globalG)) return(as.matrix(globalG[[cc]]))
  as.matrix(globalG[[i]])
}

eq_index <- function(eq_names, cc, suffix) {
  out <- match(paste0(cc, "_", suffix), eq_names)
  if (is.na(out)) out <- match(suffix, eq_names)
  out
}

stabilize_cov <- function(S, eps = 1e-10) {
  S <- as.matrix(S)
  S <- (S + t(S)) / 2
  ev <- eigen(S, symmetric = TRUE, only.values = TRUE)$values
  mn <- min(ev)
  if (!is.finite(mn)) stop("Non-finite covariance eigenvalue.")
  if (mn <= eps) S <- S + diag(abs(mn) + eps, nrow(S))
  S
}

spectral_radius <- function(F) {
  if (!length(F)) stop("No transition matrices.")
  K <- nrow(F[[1]])
  p <- length(F)
  if (p == 1L) return(as.numeric(max(Mod(eigen(F[[1]], only.values = TRUE)$values))))
  top <- do.call(cbind, F)
  lower <- cbind(diag(K * (p - 1L)), matrix(0, K * (p - 1L), K))
  companion <- rbind(top, lower)
  as.numeric(max(Mod(eigen(companion, only.values = TRUE)$values)))
}

qsum <- function(x) {
  x <- x[is.finite(x)]
  if (!length(x)) {
    return(c(low90=NA_real_, low68=NA_real_, median=NA_real_, high68=NA_real_, high90=NA_real_, mean=NA_real_, positive_share=NA_real_, negative_share=NA_real_, n=0))
  }
  qq <- quantile(x, c(.05,.16,.50,.84,.95), names = FALSE)
  c(
    low90=qq[1], low68=qq[2], median=qq[3], high68=qq[4], high90=qq[5],
    mean=mean(x), positive_share=mean(x>0), negative_share=mean(x<0), n=length(x)
  )
}

# -----------------------------------------------------------------------------
# Coefficient switch-offs
# -----------------------------------------------------------------------------
mutate_rate_switch <- function(lam0, lam_lags, cc, eq_names, wex_names, scenario) {
  if (scenario == "FULL" || scenario == "RATE_CF3_freeze_all_country_rate_path" || cc == "GL") {
    return(list(lam0=lam0, lam_lags=lam_lags))
  }
  if (!identical(wex_names, expected_wex)) {
    stop("Unexpected Wex order for ", cc, ": ", paste(wex_names, collapse=", "))
  }
  fr_j <- match("foreign_r", wex_names)
  deq_i <- eq_index(eq_names, cc, "deq")
  if (is.na(fr_j) || is.na(deq_i)) stop("Cannot locate foreign_r/equity equation for ", cc)

  if (scenario == "RATE_CF1_zero_current_foreign_rate_to_equity") {
    lam0[deq_i, fr_j] <- 0
  } else if (scenario == "RATE_CF2_zero_current_and_lag1_foreign_rate_to_equity") {
    lam0[deq_i, fr_j] <- 0
    if (!length(lam_lags) || ncol(lam_lags[[1]]) == 0L) stop("Lag-1 Wex block missing for ", cc)
    lam_lags[[1]][deq_i, fr_j] <- 0
  } else {
    stop("Unknown rate scenario: ", scenario)
  }
  list(lam0=lam0, lam_lags=lam_lags)
}

# -----------------------------------------------------------------------------
# Rebuild G/H/F for one posterior draw
# -----------------------------------------------------------------------------
build_state <- function(tt, draw, scenario) {
  locals <- vector("list", length(units))

  for (i in seq_along(units)) {
    cc <- units[[i]]
    A4 <- predDens[[i]]$ALPHA
    A_draw <- A4[, , , draw, drop = FALSE]
    A_draw <- array(A_draw, dim=dim(A4)[1:3], dimnames=dimnames(A4)[1:3])
    V <- split_alpha(A_draw)
    k_i <- length(V$eq)
    Wi <- get_W(i, cc)
    if (nrow(Wi) < k_i) stop("W has fewer rows than own variables for ", cc)

    expected_foreign <- nrow(Wi) - k_i
    if (cc == "GL") {
      if (expected_foreign != 0L) stop("GL should have zero weakly-exogenous rows.")
      wex_names <- character(0)
    } else {
      if (expected_foreign != 7L) stop("Expected 7 Wex rows for ", cc, "; found ", expected_foreign)
      if (is.null(rownames(Wi))) stop("W matrix lacks row names for ", cc)
      wex_names <- rownames(Wi)[(k_i+1L):nrow(Wi)]
      if (!identical(wex_names, expected_wex)) {
        stop("Wex row order mismatch for ", cc, ". Found: ", paste(wex_names, collapse=", "))
      }
    }

    lam0 <- slice_coef(V$Lambda0, tt, k_i)
    lam_lags <- lapply(seq_len(V$p), function(kk) slice_coef(V$Lambda[[kk]], tt, k_i))

    # q=1 in the current dominant-unit architecture. For p=2, Wexlag2 is zero.
    for (kk in seq_len(V$p)) {
      if (ncol(lam_lags[[kk]]) == 0L && expected_foreign > 0L) {
        if (kk <= 1L) stop("Missing Wexlag1 block for ", cc)
        lam_lags[[kk]] <- matrix(0, nrow=k_i, ncol=expected_foreign)
      }
      if (ncol(lam_lags[[kk]]) != expected_foreign) {
        stop("Foreign-lag/W mismatch for ", cc, " lag ", kk)
      }
    }

    sw <- mutate_rate_switch(lam0, lam_lags, cc, V$eq, wex_names, scenario)
    lam0 <- sw$lam0
    lam_lags <- sw$lam_lags

    A0 <- cbind(diag(k_i), -lam0)
    if (ncol(A0) != nrow(Wi)) stop("A0/W mismatch for ", cc, " under ", scenario)

    H_i <- vector("list", V$p)
    for (kk in seq_len(V$p)) {
      theta <- slice_coef(V$Theta[[kk]], tt, k_i)
      B <- cbind(theta, lam_lags[[kk]])
      if (ncol(B) != nrow(Wi)) stop("B/W mismatch for ", cc, " lag ", kk, " under ", scenario)
      H_i[[kk]] <- B %*% Wi
    }

    S4 <- predDens[[i]]$SIGMApost
    S <- S4[tt, , , draw, drop = FALSE]
    S <- matrix(S, nrow=k_i, ncol=k_i)
    locals[[i]] <- list(G=A0 %*% Wi, H=H_i, S=S, k=k_i)
  }

  max_p <- max(vapply(locals, function(z) length(z$H), integer(1)))
  G <- do.call(rbind, lapply(locals, `[[`, "G"))
  H <- lapply(seq_len(max_p), function(kk) {
    do.call(rbind, lapply(locals, function(z) {
      if (kk <= length(z$H)) z$H[[kk]] else matrix(0, nrow=z$k, ncol=ncol(G))
    }))
  })
  F <- lapply(H, function(h) solve(G, h))
  S_post <- lapply(locals, `[[`, "S")
  rho <- if (check_cf_stability) spectral_radius(F) else NA_real_
  list(G=G, H=H, F=F, S=S_post, rho=rho)
}

# Structural innovation in the dominant block: GL_gpr -> GL_vix.
make_structural_innovation <- function(state) {
  gl_i <- match("GL", units)
  S_gl <- stabilize_cov(state$S[[gl_i]])
  if (!all(dim(S_gl) == c(2L,2L))) stop("Dominant covariance must be 2x2.")
  L <- t(chol(S_gl))
  shock_gl <- L[,1]
  u <- unlist(lapply(seq_along(units), function(i) {
    k_i <- nrow(state$S[[i]])
    if (i == gl_i) shock_gl else rep(0, k_i)
  }), use.names=FALSE)
  if (length(u) != ncol(xglobal)) stop("Innovation stack dimension mismatch.")
  u
}

normalize_impact <- function(impact_raw, shock_pct) {
  gpr_j <- match("GL_gpr", var_names)
  if (is.na(gpr_j) || !is.finite(impact_raw[gpr_j]) || abs(impact_raw[gpr_j]) < 1e-12) {
    stop("Cannot normalize GL_gpr impact.")
  }
  target <- log1p(shock_pct/100)
  impact_raw * (target / impact_raw[gpr_j])
}

make_structural_irf <- function(state, horizon, shock_pct) {
  K <- ncol(xglobal)
  u <- make_structural_innovation(state)
  impact <- normalize_impact(as.numeric(solve(state$G, u)), shock_pct)
  out <- matrix(0, nrow=K, ncol=horizon+1L, dimnames=list(var_names, as.character(0:horizon)))
  out[,1L] <- impact
  if (horizon >= 1L) {
    for (h in seq_len(horizon)) {
      for (lag in seq_len(min(length(state$F), h))) {
        out[,h+1L] <- out[,h+1L] + state$F[[lag]] %*% out[,h-lag+1L]
      }
    }
  }
  out
}

# Strong mechanism intervention: set every country rate response to zero at
# every horizon. Replace rate equations by r_i(h)=0 and solve all remaining
# equations. This also removes indirect propagation from the rate path.
make_rate_frozen_irf <- function(state, horizon, shock_pct) {
  K <- ncol(xglobal)
  rate_idx <- match(rate_vars, var_names)
  if (anyNA(rate_idx)) stop("Cannot locate all country rate variables.")
  free_idx <- setdiff(seq_len(K), rate_idx)
  if (!(match("GL_gpr", var_names) %in% free_idx)) stop("GL_gpr unexpectedly constrained.")

  Gff <- state$G[free_idx, free_idx, drop=FALSE]
  if (nrow(Gff) != length(free_idx)) stop("Constrained G dimension mismatch.")

  # Under r=0, only non-rate columns of lag matrices remain relevant.
  Hff <- lapply(state$H, function(hh) hh[free_idx, free_idx, drop=FALSE])
  Fff <- lapply(Hff, function(hh) solve(Gff, hh))
  rho <- if (check_cf_stability) spectral_radius(Fff) else NA_real_

  u <- make_structural_innovation(state)
  impact_free_raw <- as.numeric(solve(Gff, u[free_idx]))
  impact_raw <- rep(0, K)
  impact_raw[free_idx] <- impact_free_raw
  impact <- normalize_impact(impact_raw, shock_pct)
  impact[rate_idx] <- 0

  out <- matrix(0, nrow=K, ncol=horizon+1L, dimnames=list(var_names, as.character(0:horizon)))
  out[,1L] <- impact

  if (horizon >= 1L) {
    for (h in seq_len(horizon)) {
      rhs_free <- rep(0, length(free_idx))
      for (lag in seq_len(min(length(state$H), h))) {
        rhs_free <- rhs_free + Hff[[lag]] %*% out[free_idx, h-lag+1L]
      }
      out[free_idx, h+1L] <- as.numeric(solve(Gff, rhs_free))
      out[rate_idx, h+1L] <- 0
    }
  }

  list(path=out, rho=rho)
}

