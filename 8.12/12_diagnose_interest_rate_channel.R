    rr <- rr + 1L
    rows[[rr]] <- data.frame(
      date=selected_dates[d_i], scenario=scenarios[s_i], country=country_units[c_i],
      variable=paste0(country_units[c_i],"_deq"), representation=representation,
      horizon=focus_h[h_i], median=qs[["median"]], mean=qs[["mean"]],
      low68=qs[["low68"]], high68=qs[["high68"]], low90=qs[["low90"]], high90=qs[["high90"]],
      positive_share=qs[["positive_share"]], negative_share=qs[["negative_share"]], draws=as.integer(qs[["n"]]),
      stringsAsFactors=FALSE
    )
  }
  do.call(rbind,rows)
}

